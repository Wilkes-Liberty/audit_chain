#!/usr/bin/env bash
# Build OpenSSL 3.0 with enable-fips and write a config that makes the
# fips provider the default. Used by the GitHub Actions FIPS job.
#
# The validated FIPS module is a separate artifact from ubuntu-latest's
# libssl. This script installs a prefix under $OPENSSL_FIPS_PREFIX
# (default: $HOME/openssl-fips), runs `openssl fipsinstall`, and writes
# OPENSSL_CONF / OPENSSL_MODULES / LD_LIBRARY_PATH so PHP's openssl
# extension loads that prefix. The job that sources those variables must
# still run tests/scripts/assert-openssl-fips.php; a skipped build must
# not look green.
set -euo pipefail

PREFIX="${OPENSSL_FIPS_PREFIX:-$HOME/openssl-fips}"
VERSION="${OPENSSL_FIPS_VERSION:-3.0.16}"
SRC_URL="https://www.openssl.org/source/openssl-${VERSION}.tar.gz"
SRC_FALLBACK="https://github.com/openssl/openssl/releases/download/openssl-${VERSION}/openssl-${VERSION}.tar.gz"

mkdir -p "$PREFIX"

fips_so="$PREFIX/lib/ossl-modules/fips.so"
if [[ ! -f "$fips_so" ]]; then
  work="$(mktemp -d)"
  trap 'rm -rf "$work"' EXIT
  tarball="$work/openssl.tar.gz"
  if ! curl -fsSL "$SRC_URL" -o "$tarball"; then
    curl -fsSL "$SRC_FALLBACK" -o "$tarball"
  fi
  tar -xzf "$tarball" -C "$work"
  src_dir="$work/openssl-${VERSION}"
  if [[ ! -d "$src_dir" ]]; then
    src_dir="$(find "$work" -maxdepth 1 -type d -name 'openssl-*' | head -n 1)"
  fi
  (
    cd "$src_dir"
    # --libdir=lib keeps the layout stable across amd64 / arm64 so the
    # cache key does not have to guess lib vs lib64.
    ./Configure enable-fips --prefix="$PREFIX" --libdir=lib
    make -j"$(nproc)"
    # install_sw copies libcrypto and legacy.so but not the FIPS
    # module. install_fips is the extra target that puts fips.so in
    # lib/ossl-modules.
    make install_sw install_ssldirs install_fips
  )
  trap - EXIT
  rm -rf "$work"
fi

if [[ ! -f "$fips_so" ]]; then
  echo "OpenSSL FIPS module missing at $fips_so" >&2
  exit 1
fi

# fipsinstall binds the module MAC to this prefix. Re-run after a cache
# restore so a stale fipsmodule.cnf cannot silently disable the provider.
mkdir -p "$PREFIX/ssl"
"$PREFIX/bin/openssl" fipsinstall \
  -module "$fips_so" \
  -out "$PREFIX/ssl/fipsmodule.cnf" \
  -provider_name fips

# Do not activate the default provider. That would let MD5 succeed and
# hide a non-FIPS run. The base provider stays for PEM encoding.
cat > "$PREFIX/ssl/openssl-fips.cnf" <<EOF
# Generated by tests/scripts/setup-openssl-fips.sh. Not an install default.
config_diagnostics = 1
openssl_conf = openssl_init

.include $PREFIX/ssl/fipsmodule.cnf

[openssl_init]
providers = provider_sect
alg_section = algorithm_sect

[provider_sect]
fips = fips_sect
base = base_sect

[base_sect]
activate = 1

[algorithm_sect]
default_properties = fips=yes
EOF

conf="$PREFIX/ssl/openssl-fips.cnf"
modules="$PREFIX/lib/ossl-modules"
lib="$PREFIX/lib"

export OPENSSL_CONF="$conf"
export OPENSSL_MODULES="$modules"
export LD_LIBRARY_PATH="${lib}${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
export PATH="$PREFIX/bin:$PATH"
export OPENSSL_FIPS_PREFIX="$PREFIX"

if [[ -n "${GITHUB_ENV:-}" ]]; then
  {
    echo "OPENSSL_CONF=$conf"
    echo "OPENSSL_MODULES=$modules"
    echo "LD_LIBRARY_PATH=$LD_LIBRARY_PATH"
    echo "OPENSSL_FIPS_PREFIX=$PREFIX"
  } >> "$GITHUB_ENV"
fi
if [[ -n "${GITHUB_PATH:-}" ]]; then
  echo "$PREFIX/bin" >> "$GITHUB_PATH"
fi

echo "OpenSSL FIPS prefix: $PREFIX"
echo "OPENSSL_CONF=$conf"
"$PREFIX/bin/openssl" version
"$PREFIX/bin/openssl" list -providers | tee "$PREFIX/ssl/providers.txt"
